"""The generator's ground truth for the report's flags: which nodes it changed, and when.

Every behaviour change the generator injects into activity levels is derived here from the
seed and the same functions the generator uses (``story_factor``, ``is_drifter``), so the
truth cannot drift from the data. Nothing here writes into ``sources/``: generated bytes
stay identical, and ``ground_truth.json`` sits beside them in the data directory.

Two stories and one calendar:

- **District volume.** From STORY_START's following week the first story district's
  volume falls 5% a week and the second's rises, for seven weeks (to −35% and +35%). A
  node's effect is the advisor-weighted mean of the story factor at full size, minus one.
  Activity is credited to the advisor's as-of branch, as in the marts.
- **Portfolio drift.** DRIFT_SHARE of advisors concentrate on fewer clients from
  DRIFT_START, ramping over DRIFT_DAYS, so their portfolios' 12-month contacted rate
  slides. A node's exposure is the share of its portfolio clients (by transit, as in the
  marts) held by a drifter when the ramp ends; its effect is that share above the bank's.
- **Calendar.** Holiday weeks and the February lift change volume by design (DQ031 uses the
  same factors). Their flags are counted separately and still count as false alarms.

A story is *scored* (counts for recall) when its effect clears ``MIN_VOLUME_EFFECT`` or
``MIN_DRIFT_EXCESS``. A smaller exposure still explains a flag that points its way, so it
is a precision positive without entering story recall. See ADR 0006.
"""

from __future__ import annotations

import json
from collections import Counter, defaultdict
from collections.abc import Sequence
from dataclasses import asdict, dataclass
from datetime import date, timedelta
from pathlib import Path

from pulse.business_calendar import week_factor
from pulse.contracts.enums import ClientStatus, Role
from pulse.generate.activity import (
    DRIFT_DAYS,
    DRIFT_START,
    STORY_START,
    default_story_districts,
    is_drifter,
    story_factor,
)
from pulse.generate.advisors import AssignmentRow
from pulse.generate.clients import ClientBatch
from pulse.generate.portfolios import PortfolioBatch, holders_on
from pulse.reference import OrgReference

TRUTH_FILE = "ground_truth.json"
VOLUME_KPIS = ("ACT_PER_ADV", "CALLS_OUT", "APPT_BOOKED", "CLIENTS_CONTACTED")
DRIFT_KPIS = ("PRTF_CONTACT_12M",)
# Full-size effects below these explain a flag but are too small to count as a story.
MIN_VOLUME_EFFECT = 0.05
MIN_DRIFT_EXCESS = 0.10
# How long after reaching full size a story can still be flagged: a level shift stays
# unusual until the 13-week baseline has absorbed it; a slipping 12-month rate keeps
# slipping until a whole year has rolled over the change.
VOLUME_SETTLE_WEEKS = 13
DRIFT_SETTLE_WEEKS = 52
LEVELS = ("NATIONAL", "REGION", "DISTRICT", "BRANCH")
TRUTH_LEVELS = (*LEVELS, "ADVISOR")


@dataclass(frozen=True)
class Story:
    story: str  # DISTRICT_VOLUME or PORTFOLIO_DRIFT
    level: str
    node_id: str
    direction: str  # UP or DOWN
    kpis: tuple[str, ...]  # the measures it moves directly
    related_kpis: tuple[str, ...]  # measures it moves slowly or a little
    start_week: str  # the first week the generator's change is in the data
    full_week: str  # the week the change reaches full size
    end_week: str  # the last week a flag can still be credited to it
    effect: float
    scored: bool


@dataclass(frozen=True)
class GroundTruth:
    seed: int
    stories: tuple[Story, ...]
    calendar_weeks: tuple[str, ...]

    def to_json(self) -> str:
        return json.dumps(asdict(self), indent=2) + "\n"


def _advisor_stories(
    org: OrgReference, assignments: Sequence[AssignmentRow], seed: int, last: date
) -> list[Story]:
    """Source events, including advisors absent from the four-level flag report.

    Volume events follow assignment ranges, so a transfer into a story district starts
    exposure on the transfer date. Drift is advisor-specific and starts on the first
    eligible working day, including advisors hired after the global start. Advisor events
    do not enter report recall because the mart has no advisor-level flag rows.
    """
    districts = {p.branch.branch_id: p.district.district_code for p in org.placements()}
    changed = STORY_START + timedelta(weeks=1)
    full = STORY_START + timedelta(weeks=7)
    drift_first: dict[str, date] = {}
    events = []
    for advisor, branch, role, start, end in assignments:
        if role == Role.BRANCH_MANAGER:
            continue
        until = (
            min(last + timedelta(days=6), end - timedelta(days=1))
            if end
            else last + timedelta(days=6)
        )
        first = _first_weekday_after(max(start, changed) - timedelta(days=1))
        if first <= until:
            effect = story_factor(districts[branch], default_story_districts(org), 7) - 1
            if effect:
                events.append(
                    Story(
                        story="DISTRICT_VOLUME",
                        level="ADVISOR",
                        node_id=advisor,
                        direction="UP" if effect > 0 else "DOWN",
                        kpis=VOLUME_KPIS,
                        related_kpis=DRIFT_KPIS,
                        start_week=iso_week(first),
                        full_week=iso_week(max(first, min(full, until))),
                        end_week=iso_week(until),
                        effect=round(effect, 4),
                        scored=False,
                    )
                )
        first = max(start, _first_weekday_after(DRIFT_START))
        while first.weekday() >= 5:
            first += timedelta(days=1)
        if first <= until and is_drifter(seed, advisor):
            drift_first[advisor] = min(first, drift_first.get(advisor, first))
    for advisor, first in sorted(drift_first.items()):
        events.append(
            Story(
                story="PORTFOLIO_DRIFT",
                level="ADVISOR",
                node_id=advisor,
                direction="DOWN",
                kpis=DRIFT_KPIS,
                related_kpis=("CLIENTS_CONTACTED",),
                start_week=iso_week(first),
                full_week=iso_week(max(first, DRIFT_START + timedelta(days=DRIFT_DAYS))),
                end_week=iso_week(
                    DRIFT_START + timedelta(days=DRIFT_DAYS, weeks=DRIFT_SETTLE_WEEKS)
                ),
                effect=-1.0,
                scored=False,  # wholly exposed to the seeded drift, not a rate prediction
            )
        )
    return events


def iso_week(day: date) -> str:
    calendar = day.isocalendar()
    return f"{calendar.year}-W{calendar.week:02d}"


def _monday(day: date) -> date:
    return day - timedelta(days=day.weekday())


def _first_weekday_after(day: date) -> date:
    day += timedelta(days=1)
    while day.weekday() >= 5:
        day += timedelta(days=1)
    return day


def _node_map(org: OrgReference) -> dict[str, tuple[tuple[str, str], ...]]:
    """Every branch's nodes in the report, one per level."""
    return {
        p.branch.branch_id: (
            ("NATIONAL", org.national.node_id),
            ("REGION", str(p.region.region_code)),
            ("DISTRICT", p.district.district_code),
            ("BRANCH", p.branch.branch_id),
        )
        for p in org.placements()
    }


def _volume_stories(org: OrgReference, assignments: Sequence[AssignmentRow]) -> list[Story]:
    story_districts = default_story_districts(org)
    districts = {p.branch.branch_id: p.district.district_code for p in org.placements()}
    first = STORY_START + timedelta(weeks=1)  # step 1, the first changed week
    full = STORY_START + timedelta(weeks=7)
    nodes = _node_map(org)
    weights: dict[tuple[str, str], list[float]] = defaultdict(list)
    for _advisor, branch, role, start, end in assignments:
        if role == Role.BRANCH_MANAGER or start > full or (end is not None and full >= end):
            continue
        factor = story_factor(districts[branch], story_districts, 7)
        for node in nodes[branch]:
            weights[node].append(factor)
    stories = []
    for (level, node_id), factors in sorted(weights.items()):
        effect = round(sum(factors) / len(factors) - 1, 4)
        if effect == 0:
            continue
        stories.append(
            Story(
                story="DISTRICT_VOLUME",
                level=level,
                node_id=node_id,
                direction="UP" if effect > 0 else "DOWN",
                kpis=VOLUME_KPIS,
                related_kpis=DRIFT_KPIS,
                start_week=iso_week(first),
                full_week=iso_week(full),
                end_week=iso_week(full + timedelta(weeks=VOLUME_SETTLE_WEEKS)),
                effect=effect,
                scored=abs(effect) >= MIN_VOLUME_EFFECT,
            )
        )
    return stories


def _drift_stories(
    org: OrgReference, seed: int, clients: ClientBatch, portfolios: PortfolioBatch
) -> list[Story]:
    full_day = DRIFT_START + timedelta(days=DRIFT_DAYS)
    state = {client.client_id: client for client in clients.snapshot}
    for change in clients.changes:
        if change.day <= full_day:
            state[change.after.client_id] = change.after
    holders = holders_on(portfolios, full_day)
    transit = {p.portfolio_id: p.branch_id for p in portfolios.master}
    nodes = _node_map(org)
    held: Counter[tuple[str, str]] = Counter()
    drifting: Counter[tuple[str, str]] = Counter()
    for client in state.values():
        if client.status_code is not ClientStatus.ACTIVE or client.client_since_date > full_day:
            continue
        holder = holders.get(client.portfolio_id)
        branch = transit.get(client.portfolio_id)
        if holder is None or branch is None:
            continue
        for node in nodes[branch]:
            held[node] += 1
            drifting[node] += is_drifter(seed, holder)
    bank = drifting[("NATIONAL", org.national.node_id)] / held[("NATIONAL", org.national.node_id)]
    stories = []
    for (level, node_id), total in sorted(held.items()):
        excess = round(drifting[(level, node_id)] / total - bank, 4)
        if excess <= 0:
            continue
        stories.append(
            Story(
                story="PORTFOLIO_DRIFT",
                level=level,
                node_id=node_id,
                direction="DOWN",
                kpis=DRIFT_KPIS,
                related_kpis=("CLIENTS_CONTACTED",),
                start_week=iso_week(_first_weekday_after(DRIFT_START)),
                full_week=iso_week(full_day),
                end_week=iso_week(full_day + timedelta(weeks=DRIFT_SETTLE_WEEKS)),
                effect=-excess,
                scored=excess >= MIN_DRIFT_EXCESS,
            )
        )
    return stories


def calendar_weeks(first: date, last: date) -> tuple[str, ...]:
    """Weeks whose expected volume differs from an ordinary week, and the weeks after them."""
    weeks: list[str] = []
    monday = _monday(first)
    while monday <= last:
        this, before = iso_week(monday), iso_week(monday - timedelta(weeks=1))
        if week_factor(this) != 1.0 or week_factor(before) != 1.0:
            weeks.append(this)
        monday += timedelta(weeks=1)
    return tuple(weeks)


def ground_truth(
    org: OrgReference,
    assignments: Sequence[AssignmentRow],
    clients: ClientBatch,
    portfolios: PortfolioBatch,
    *,
    seed: int,
    first: date,
    last: date,
) -> GroundTruth:
    """Every injected behaviour change, from the seed and the generator's own functions."""
    stories = _volume_stories(org, assignments) + _drift_stories(org, seed, clients, portfolios)
    stories += _advisor_stories(org, assignments, seed, last)
    stories.sort(key=lambda s: (s.story, TRUTH_LEVELS.index(s.level), s.node_id, s.start_week))
    return GroundTruth(
        seed=seed, stories=tuple(stories), calendar_weeks=calendar_weeks(first, last)
    )


def write_ground_truth(truth: GroundTruth, data_dir: Path) -> Path:
    path = data_dir / TRUTH_FILE
    path.write_text(truth.to_json(), encoding="utf-8")
    return path
