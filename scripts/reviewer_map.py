"""Build the reviewer's competency map from extracted skills, never stored job text.

Run `uv run python scripts/reviewer_map.py [--check]`. Counts are observed mentions,
including preferred skills, in an owner-selected historical sample; they are not a
market survey, current-vacancy count, or proof of professional experience.
"""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path
from urllib.parse import unquote, urlsplit

ROOT = Path(__file__).resolve().parents[1]
REPO = "https://github.com/welkincz/advisor-pulse/blob/main/"
SITE = "https://pulse.charliebuild.com"


def normalize(skill: str) -> str:
    key = re.sub(r"[^a-z0-9]+", "_", skill.casefold()).strip("_")
    return {"t_sql": "sql", "spark_sql": "sql", "py_spark": "pyspark"}.get(key, key)


def counts(postings: list[dict], tags: list[str]) -> dict:
    wanted = {normalize(tag) for tag in tags}
    found = [p for p in postings if wanted & {normalize(s) for s in p["skills"]}]
    return {
        "total": len(found),
        "retrieved": sum(p["basis"] == "retrieved" for p in found),
        "AE": sum(p["lane"] == "AE" for p in found),
        "DE": sum(p["lane"] == "DE" for p in found),
        "ids": [p["id"] for p in found],
    }


def check_link(root: Path, link: str) -> None:
    """Check local file/line evidence and concrete site routes without network in CI."""
    if link.startswith(REPO):
        link = link.removeprefix(REPO)
    elif link.startswith(SITE + "/"):
        path = urlsplit(link).path
        router = (root / "web/src/app/App.tsx").read_text()
        routes = re.findall(r'<Route\s+path="([^"]+)"', router)
        patterns = [
            "/".join("[^/]+" if s.startswith(":") else re.escape(s) for s in r.split("/"))
            for r in routes
            if r != "*" and not r.startswith("/_")
        ]
        if not any(re.fullmatch(p, path) for p in patterns):
            raise ValueError(f"Unknown site route: {link}")
        return
    elif urlsplit(link).scheme:
        raise ValueError(f"Unsupported evidence URL: {link}")
    parts = urlsplit(link)
    target = (root / unquote(parts.path)).resolve()
    if not target.is_relative_to(root.resolve()) or not target.exists():
        raise ValueError(f"Missing evidence file: {link}")
    if parts.fragment:
        match = re.fullmatch(r"L([1-9]\d*)", parts.fragment)
        if (
            not match
            or not target.is_file()
            or int(match[1]) > len(target.read_text().splitlines())
        ):
            raise ValueError(f"Invalid evidence line: {link}")


def validate(root: Path, data: dict) -> None:
    postings = data["postings"]
    ids = [p["id"] for p in postings]
    if not 8 <= len(postings) <= 12 or len(ids) != len(set(ids)):
        raise ValueError("Use 8–12 postings with unique source IDs")
    for post in postings:
        if post["lane"] not in ("AE", "DE") or post["basis"] not in ("retrieved", "owner_summary"):
            raise ValueError(f"Invalid source classification: {post['id']}")
        if not post["url"].startswith("https://") or not isinstance(post["skills"], list):
            raise ValueError(f"Invalid extracted skills: {post['id']}")
    for item in data["competencies"]:
        if item["strength"] not in ("strong", "weak", "missing"):
            raise ValueError(f"Invalid strength: {item['name']}")
        if item["strength"] != "strong" and not item.get("gap_issue"):
            raise ValueError(f"Gap needs its own issue: {item['name']}")
        for link in item["evidence"]:
            check_link(root, link)
    for name in ("README.md", "docs/case-study.md"):
        source = Path(name)
        text = (root / source).read_text()
        section = re.search(r"^## For reviewers[^\n]*\n(.*?)(?=^## |\Z)", text, re.M | re.S)
        steps = re.findall(r"^\d+\. (.+)$", section[1], re.M) if section else []
        if not steps:
            raise ValueError(f"Missing reviewer path: {name}")
        for step in steps:
            links = re.findall(r"\[[^\]]+\]\(([^)]+)\)", step)
            if len(links) != 1:
                raise ValueError(f"Each reviewer step needs one link: {name}")
            link = links[0]
            check_link(root, link if urlsplit(link).scheme else str(source.parent / link))


def render(data: dict) -> str:
    posts = data["postings"]
    retrieved = sum(p["basis"] == "retrieved" for p in posts)
    unknown = ", ".join(p["id"] for p in posts if not p["skills"])
    out = [
        "# A reviewer's map of Advisor Pulse",
        "",
        "<!-- Generated by scripts/reviewer_map.py from reviewer-skills.json; edit inputs. -->",
        "",
        f"Skill extraction snapshot: {data['as_of']}. {len(posts)} owner-supplied roles, "
        f"{sum(p['lane'] == 'AE' for p in posts)} AE / adjacent and "
        f"{sum(p['lane'] == 'DE' for p in posts)} DE; {retrieved} descriptions retrieved, "
        "the remainder "
        f"retained only as owner summaries. No extractable skill list: {unknown or 'none'}.",
        "",
        "This is a selected historical sample, including expired or inaccessible roles. "
        "Counts are lower-bound observed mentions (required or preferred), once per posting "
        "and competency; an absent tag means unknown, not an employer rejecting that skill. "
        "AE/DE is the owner's classification. These counts do not establish market prevalence, "
        "salary, vacancy status, or interview readiness.",
        "",
        "Strong means inspectable implementation and tests within this synthetic project. "
        "Weak means partial or transferable evidence; missing means no direct implementation. "
        "No grade claims employment experience, regulated deployment, adoption, "
        "or business impact.",
        "",
        "## Individual tool mentions",
        "",
        "PySpark is counted separately from Python; a skill inferred from another tool "
        "does not become a direct mention. These per-role lists cannot substantiate the "
        "owner's earlier aggregate of Python 11/12 and SQL 9/12.",
        "",
        f"| Tool | Observed / {len(posts)} | Retrieved / {retrieved} | Source IDs |",
        "|---|---|---|---|",
    ]
    for tool in ("python", "sql", "pyspark", "databricks", "airflow", "aws", "snowflake", "dbt"):
        n = counts(posts, [tool])
        out.append(f"| {tool} | {n['total']} | {n['retrieved']} | {', '.join(n['ids'])} |")
    out += [
        "",
        "## Competencies and evidence",
        "",
        "The retrieved column counts only roles whose skill description was read in this "
        "continuation (employer pages, employer-posted listings or identified syndication). "
        "Source IDs make each count traceable to the extracted list below.",
        "",
        f"| Competency | Mentions / {len(posts)} (AE / DE) | Retrieved / {retrieved} "
        "| Evidence | Strength and limits | Gap |",
        "|---|---|---|---|---|---|",
    ]
    for item in data["competencies"]:
        n = counts(posts, item["tags"])
        links = (
            ", ".join(
                f"[{link.rsplit('/', 1)[-1].replace('#', ':') or 'report'}]"
                f"({link if link.startswith('https:') else REPO + link})"
                for link in item["evidence"]
            )
            or "No direct implementation"
        )
        gap = (
            f"[#{item['gap_issue']}](https://github.com/welkincz/advisor-pulse/issues/{item['gap_issue']})"
            if item.get("gap_issue")
            else "—"
        )
        out.append(
            f"| {item['name']} | {n['total']} ({n['AE']} / {n['DE']}); "
            f"{', '.join(n['ids']) or 'none'} | {n['retrieved']} | {links} | "
            f"**{item['strength']}**: {item['limit']} | {gap} |"
        )
    out += [
        "",
        "## Extracted skill lists and provenance",
        "",
        "Only the short skill lists and source metadata are stored; posting text and "
        "compensation are not retained. Source links may expire. Hiring samples are "
        "external evidence and do not supply any bank data or rules to the fictional report.",
        "",
    ]
    for p in posts:
        out.append(
            f"- **{p['id']}**, {p['lane']}, [{p['role']}]({p['url']}), "
            f"{p['basis']}: {', '.join(p['skills']) or 'no skills supplied'}. {p['note']}"
        )
    out += [
        "",
        "## Reproduce",
        "",
        "```sh",
        "uv run python scripts/reviewer_map.py --check",
        "uv run pytest tests/test_reviewer_map.py",
        "```",
        "",
    ]
    return "\n".join(out)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    data = json.loads((ROOT / "docs/reviewer-skills.json").read_text())
    validate(ROOT, data)
    text = render(data)
    dest = ROOT / "docs/reviewer-map.md"
    if args.check:
        if not dest.exists() or dest.read_text() != text:
            raise SystemExit("reviewer-map.md is stale; run scripts/reviewer_map.py")
    else:
        dest.write_text(text)
    print("Reviewer map: counts reproducible; all file/line and route evidence resolves.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
